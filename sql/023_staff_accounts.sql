create or replace function public.admin_list_staff()
returns jsonb
language plpgsql stable security definer set search_path = public, auth as $$
declare v_today date := (now() at time zone 'Asia/Bangkok')::date;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'user_id', a.user_id, 'name', public._admin_name(a.user_id), 'display_name', coalesce(a.display_name, ''),
             'email', coalesce(u.email::text, ''), 'phone', coalesce(p.phone, ''), 'role', a.role,
             'status', public._member_status(a), 'account_type', coalesce(p.account_type, 'customer'),
             'created_at', a.created_at, 'last_sign_in_at', u.last_sign_in_at, 'via_invite', a.invite_id is not null,
             'sales_rep', coalesce(r.active, false),
             'clients', (select count(*) from public.profiles c where c.sales_rep_id = a.user_id),
             'rate', (select jsonb_build_object('type', x.type, 'value', x.value, 'effective_from', x.effective_from)
                        from public.sales_rep_rates x where x.rep_id = a.user_id and x.effective_from <= v_today
                       order by x.effective_from desc, x.created_at desc, x.id desc limit 1))
           order by public._admin_role_rank(a.role) desc, a.role, a.created_at)
      from public.admins a
      left join auth.users u on u.id = a.user_id
      left join public.profiles p on p.id = a.user_id
      left join public.sales_reps r on r.user_id = a.user_id), '[]'::jsonb);
end $$;

-- 대시보드 "지금 처리할 일": 최근 7일 초대 가입 + 확인 대기 매니저
create or replace function public.admin_staff_todo()
returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.has_admin_role('owner') then return jsonb_build_object('joins', '[]'::jsonb, 'pending', '[]'::jsonb); end if;
  return jsonb_build_object(
    'joins', coalesce((select jsonb_agg(jsonb_build_object('user_id', i.used_by, 'name', public._admin_name(i.used_by), 'role', i.role, 'at', i.used_at)
                                        order by i.used_at desc)
                         from public.staff_invites i where i.used_at >= now() - interval '7 days'), '[]'::jsonb),
    'pending', coalesce((select jsonb_agg(jsonb_build_object('user_id', a.user_id, 'name', public._admin_name(a.user_id), 'role', a.role) order by a.created_at)
                           from public.admins a where a.pending_confirm and a.active), '[]'::jsonb));
end $$;

create or replace function public.admin_confirm_member(p_user uuid)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  update public.admins set pending_confirm = false where user_id = p_user and pending_confirm;
  if not found then raise exception 'NOT_MEMBER'; end if;
  perform public._audit('staff_confirmed', 'member', p_user::text, jsonb_build_object('name', public._admin_name(p_user)));
end $$;

-- 거래처 옮기기 (여러 곳 한꺼번에) — p_to null = 담당 없음
create or replace function public._move_clients(p_users uuid[], p_to uuid)
returns integer
language plpgsql security definer set search_path = public as $$
declare v_n integer;
begin
  if p_to is not null and not exists (
       select 1 from public.sales_reps r join public.admins a on a.user_id = r.user_id
        where r.user_id = p_to and r.active and a.active and not a.pending_confirm) then
    raise exception 'REP_NOT_FOUND';
  end if;
  perform set_config('allabut.rep_ok', '1', true);
  update public.profiles set sales_rep_id = p_to
   where id = any (coalesce(p_users, '{}')) and account_type <> 'staff' and sales_rep_id is distinct from p_to;
  get diagnostics v_n = row_count;
  perform set_config('allabut.rep_ok', '0', true);
  return v_n;
end $$;
