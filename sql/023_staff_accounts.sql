  select sales_rep_id into v_old from public.profiles where id = p_user for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if exists (select 1 from public.profiles where id = p_user and account_type = 'staff') then raise exception 'NOT_CUSTOMER'; end if;   -- 직원 계정은 담당 지정 대상 아님 (023)
  if p_rep is not null and not exists (select 1 from public.sales_reps where user_id = p_rep and active) then
    raise exception 'REP_NOT_FOUND';
  end if;
  if v_old is not distinct from p_rep then return jsonb_build_object('changed', false, 'rep_id', p_rep); end if;

  perform set_config('allabut.rep_ok', '1', true);
  update public.profiles set sales_rep_id = p_rep where id = p_user;
  perform set_config('allabut.rep_ok', '0', true);

  perform public._audit('customer_rep', 'customer', p_user::text, jsonb_build_object(
    'from', v_old, 'to', p_rep, 'customer', public._customer_label(p_user),
    'from_name', case when v_old is null then '' else public._admin_name(v_old) end,
    'to_name', case when p_rep is null then '' else public._admin_name(p_rep) end));
  return jsonb_build_object('changed', true, 'rep_id', p_rep);
end $$;
revoke all on function public.admin_set_customer_rep(uuid, uuid, boolean) from public, anon;
grant execute on function public.admin_set_customer_rep(uuid, uuid, boolean) to authenticated;

-- 방문 통계 (013 정의 + 가입 수에서 직원 계정 제외 → 가입 전환율)
create or replace function public.admin_visit_stats(
  p_from date, p_to date, p_no_bots boolean default false, p_no_staff boolean default false
) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_from date := coalesce(p_from, (now() at time zone 'Asia/Bangkok')::date);
  v_to date := coalesce(p_to, v_from);
  v_out jsonb;
begin
  if not public.has_admin_role('staff') then raise exception 'NOT_ADMIN'; end if;
  if v_to < v_from then raise exception 'INVALID_RANGE'; end if;
  if v_to - v_from > 400 then raise exception 'RANGE_TOO_LONG'; end if;

  with ev as (
    select * from public.site_events
     where day between v_from and v_to
       and (not coalesce(p_no_bots, false) or not is_bot)
       and (not coalesce(p_no_staff, false) or not is_staff)
  ),
  visits as (select * from ev where kind = 'visit'),
  -- 처음 본 방문자: 그 visitor_id 의 가장 첫 기록이 이 기간 안
  firsts as (
    select visitor_id, min(day) as first_day from public.site_events
     where visitor_id in (select distinct visitor_id from ev where visitor_id is not null)
     group by visitor_id
  )
  select jsonb_build_object(
    'from', v_from, 'to', v_to,
    'summary', jsonb_build_object(
      'visits', (select count(*) from visits),
      'visitors', (select count(distinct visitor_id) from ev where visitor_id is not null),
      'pageviews', (select count(*) from ev where kind = 'pageview'),
      'new_visitors', (select count(*) from firsts where first_day between v_from and v_to),
      'bot_visits', (select count(*) from visits where is_bot),
      'staff_visits', (select count(*) from visits where is_staff)),
    'daily', coalesce((
      select jsonb_agg(jsonb_build_object(
        'day', d.day,
        'visits', (select count(*) from visits v where v.day = d.day),
        'visitors', (select count(distinct visitor_id) from ev e where e.day = d.day and e.visitor_id is not null),
        'pageviews', (select count(*) from ev e where e.day = d.day and e.kind = 'pageview'),
        'bots', (select count(*) from visits v where v.day = d.day and v.is_bot),
        'staff', (select count(*) from visits v where v.day = d.day and v.is_staff)) order by d.day)
      from (select generate_series(v_from, v_to, interval '1 day')::date as day) d), '[]'::jsonb),
    'hourly', case when v_from = v_to then coalesce((
      select jsonb_agg(jsonb_build_object(
        'hour', h.hour,
        'visits', (select count(*) from visits v where extract(hour from v.created_at at time zone 'Asia/Bangkok') = h.hour),
        'visitors', (select count(distinct visitor_id) from ev e where e.visitor_id is not null and extract(hour from e.created_at at time zone 'Asia/Bangkok') = h.hour)) order by h.hour)
      from generate_series(0, 23) as h(hour)), '[]'::jsonb) else null end,
    'paths', coalesce((select jsonb_agg(jsonb_build_object('key', path, 'n', n) order by n desc, path)
      from (select path, count(*) as n from ev where kind = 'pageview' group by path order by count(*) desc, path limit 20) x), '[]'::jsonb),
    'referrers', coalesce((select jsonb_agg(jsonb_build_object('key', referrer_host, 'n', n) order by n desc, referrer_host)
      from (select referrer_host, count(*) as n from visits group by referrer_host order by count(*) desc limit 30) x), '[]'::jsonb),
    'devices', coalesce((select jsonb_agg(jsonb_build_object('key', device, 'n', n) order by n desc)
      from (select device, count(*) as n from visits group by device) x), '[]'::jsonb),
    'langs', coalesce((select jsonb_agg(jsonb_build_object('key', lang, 'n', n) order by n desc, lang)
      from (select lang, count(*) as n from visits group by lang order by count(*) desc limit 15) x), '[]'::jsonb),
    'countries', coalesce((select jsonb_agg(jsonb_build_object('key', country, 'n', n) order by n desc, country)
      from (select country, count(*) as n from visits group by country order by count(*) desc limit 15) x), '[]'::jsonb),
    -- 전환: 이 기간(방콕 날짜)에 가입한 계정 수
    'signups', (select count(*) from auth.users u
                 where (u.created_at at time zone 'Asia/Bangkok')::date between v_from and v_to
                   and not exists (select 1 from public.profiles p where p.id = u.id and p.account_type = 'staff'))   -- 직원 계정은 가입 수에서 빼요 (023)
  ) into v_out;
  return v_out;
end $$;
revoke all on function public.admin_visit_stats(date, date, boolean, boolean) from public, anon;
grant execute on function public.admin_visit_stats(date, date, boolean, boolean) to authenticated;


-- ================================================================
-- 10) 주문 · 충전 함수 맨 앞에서 STAFF_ACCOUNT (create_cnc_order = 019 정의, create_topup_request = 021 정의 + 한 줄)
--     (크레딧 부족 같은 다른 오류보다 먼저 알려줘요)
-- ================================================================
create or replace function public.create_cnc_order(
  p_patient text, p_deadline date, p_clinic text, p_addr text,
  p_phone text, p_line_id text, p_cases jsonb, p_use_free boolean default false
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_teeth integer;
  v_crown integer;
  v_cases jsonb;
  v_id text;
  v_balance integer;
  v_paid integer;
  v_free_avail integer;
  v_free_used integer := 0;
  v_free_taken integer := 0;
  v_need integer;
  v_p text;
  v_prof record;
  v_clinic text := p_clinic;
  v_addr text := p_addr;
  v_phone text := p_phone;
begin
  if exists (select 1 from public.profiles where id = auth.uid() and account_type = 'staff') then raise exception 'STAFF_ACCOUNT'; end if;   -- 023: 직원 계정은 주문 · 충전 불가
  if v_uid is null then raise exception 'NOT_LOGGED_IN'; end if;

  -- 무료 크레딧 주문: 배송 정보는 화면 값이 아니라 등록된 치과 정보로 (DB 가 정해요)
  if coalesce(p_use_free, false) then
    select reg_clinic, reg_addr, reg_phone, clinic_locked_at into v_prof from public.profiles where id = v_uid;
    if v_prof.clinic_locked_at is null then raise exception 'NO_REGISTERED_CLINIC'; end if;
    v_clinic := v_prof.reg_clinic; v_addr := v_prof.reg_addr; v_phone := v_prof.reg_phone;
  end if;

  if coalesce(trim(v_clinic), '') = '' or coalesce(trim(v_addr), '') = '' or coalesce(trim(v_phone), '') = '' then
    raise exception 'DELIVERY_REQUIRED';
  end if;

  -- 치아마다 종류를 채워 넣어요 (없으면 abutment, 모르는 값이면 INVALID_PRODUCT)
  -- 쉐이드는 크라운 세트 치아만 (019): 어버트먼트 치아는 color 를 비워서 저장
  select coalesce(jsonb_agg(
           case when jsonb_typeof(c) = 'object' then
             jsonb_set(c, '{teeth}', coalesce((
               select jsonb_agg(case when jsonb_typeof(t) = 'object'
                                     then t || jsonb_build_object('product', public._tooth_product(t))
                                            || case when public._tooth_product(t) = 'abutment' then jsonb_build_object('color', '') else '{}'::jsonb end
                                     else t end order by o)
                 from jsonb_array_elements(case when jsonb_typeof(c -> 'teeth') = 'array' then c -> 'teeth' else '[]'::jsonb end) with ordinality x(t, o)
             ), '[]'::jsonb))
           else c end order by co), '[]'::jsonb)
    into v_cases
    from jsonb_array_elements(case when jsonb_typeof(p_cases) = 'array' then p_cases else '[]'::jsonb end) with ordinality y(c, co);

  select count(*), count(*) filter (where public._tooth_product(t) = 'crown_set')
    into v_teeth, v_crown
    from jsonb_array_elements(v_cases) c,
         jsonb_array_elements(case when jsonb_typeof(c -> 'teeth') = 'array' then c -> 'teeth' else '[]'::jsonb end) t;
  if v_teeth < 1 then raise exception 'NO_TEETH'; end if;

  -- 크라운 세트 치아는 쉐이드 필수 (019) — 어버트먼트 치아는 쉐이드 없음
  if exists (select 1
               from jsonb_array_elements(v_cases) c,
                    jsonb_array_elements(case when jsonb_typeof(c -> 'teeth') = 'array' then c -> 'teeth' else '[]'::jsonb end) t
              where public._tooth_product(t) = 'crown_set'
                and coalesce(nullif(trim(t ->> 'color'), ''), nullif(trim(t ->> 'shade'), '')) is null) then
    raise exception 'SHADE_REQUIRED_CROWN_SET';
  end if;

  -- 같은 사용자의 동시 주문을 줄 세우기 (지갑 행 잠금)
  insert into public.credit_wallets (user_id, balance) values (v_uid, 0) on conflict (user_id) do nothing;
  perform 1 from public.credit_wallets where user_id = v_uid for update;
  perform public._credit_expire_lots(v_uid);

  -- 종류마다 따로 검사 (어버트먼트 크레딧으로 크라운 세트를 못 사고, 반대도 안 돼요)
  foreach v_p in array array['abutment', 'crown_set'] loop
    v_need := case when v_p = 'crown_set' then v_crown else v_teeth - v_crown end;
    continue when v_need <= 0;
    select coalesce(sum(remaining) filter (where restriction is null), 0),
           coalesce(sum(remaining) filter (where restriction is not null), 0)
      into v_paid, v_free_avail
      from public.credit_lots where user_id = v_uid and product = v_p and remaining > 0 and expires_at > now();

    if coalesce(p_use_free, false) then
      if v_paid + v_free_avail < v_need then raise exception '%', 'INSUFFICIENT_CREDITS_' || upper(v_p); end if;
    elsif v_paid < v_need then
      -- 산 크레딧은 모자라지만 무료 크레딧을 쓰면 충분 → 등록 주소로 주문해야 써요
      if v_paid + v_free_avail >= v_need and v_free_avail > 0 then raise exception 'bonus_address_only'; end if;
      raise exception '%', 'INSUFFICIENT_CREDITS_' || upper(v_p);
    end if;
    -- 무료 먼저 쓰는 수를 미리 정해서 주문과 함께 저장 (새 주문 LINE 알림이 INSERT 때 bonus_used 를 볼 수 있게)
    if coalesce(p_use_free, false) then v_free_used := v_free_used + least(v_free_avail, v_need); end if;
  end loop;

  -- 납품일은 디자인 승인 때 정해요 (012) → 새 주문은 항상 null
  v_id := 'CA' || to_char(now(), 'YYMMDD') || '-' || lpad(nextval('public.cnc_order_seq')::text, 4, '0');
  insert into public.cnc_orders (id, user_id, patient, deadline, clinic, addr, phone, line_id, cases, teeth_count, credits_used, addr_norm, bonus_used, crown_set_count)
  values (v_id, v_uid, coalesce(p_patient, ''), null, trim(v_clinic), trim(v_addr), trim(v_phone), coalesce(p_line_id, ''), v_cases, v_teeth, v_teeth,
          public._norm_addr(v_addr), v_free_used, v_crown);

  foreach v_p in array array['abutment', 'crown_set'] loop
    v_need := case when v_p = 'crown_set' then v_crown else v_teeth - v_crown end;
    continue when v_need <= 0;
    v_free_taken := v_free_taken + public._credit_take_mode(v_uid, v_need, v_id,
                      case when coalesce(p_use_free, false) then 'free_first' else 'paid' end, v_p);
  end loop;
  if v_free_taken <> v_free_used then
    raise exception 'CREDIT_SPLIT_MISMATCH';   -- 일어나면 안 돼요 (지갑 행을 잠가서 그 사이 바뀌지 않아요)
  end if;
  v_balance := public._credit_recalc(v_uid);
  insert into public.credit_history (user_id, amount, type, order_id, description)
  values (v_uid, -v_teeth, 'use', v_id, 'CNC order ' || v_id || ' (' || v_teeth || ' teeth'
          || case when v_crown > 0 then ', ' || v_crown || ' crown set' else '' end
          || case when v_free_used > 0 then ', ' || v_free_used || ' free' else '' end || ')');

  return jsonb_build_object('id', v_id, 'teeth', v_teeth, 'balance', v_balance, 'bonus_used', v_free_used,
                            'abutment', v_teeth - v_crown, 'crown_set', v_crown,
                            'balance_crown_set', (select balance_crown_set from public.credit_wallets where user_id = v_uid));
end $$;

create or replace function public.create_topup_request(p_package_id bigint, p_slip_path text)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_pkg record;
  v_vat numeric;
  v_sub numeric;
  v_vat_amt numeric;
  v_id text;
begin
  if exists (select 1 from public.profiles where id = auth.uid() and account_type = 'staff') then raise exception 'STAFF_ACCOUNT'; end if;   -- 023: 직원 계정은 주문 · 충전 불가
  if v_uid is null then raise exception 'NOT_LOGGED_IN'; end if;
  select * into v_pkg from public.credit_packages where id = p_package_id and active;
  if not found then raise exception 'PACKAGE_NOT_FOUND'; end if;

  -- 슬립 파일은 본인 폴더에 실제로 올라가 있어야 해요
  if p_slip_path is null or split_part(p_slip_path, '/', 1) <> v_uid::text or p_slip_path like '%..%' or length(p_slip_path) > 300 then
    raise exception 'SLIP_INVALID';
  end if;
  if not exists (select 1 from storage.objects where bucket_id = 'topup-slips' and name = p_slip_path) then
    raise exception 'SLIP_NOT_FOUND';
  end if;
  if (select count(*) from public.topup_requests where user_id = v_uid and status = 'pending') >= 5 then
    raise exception 'TOO_MANY_PENDING';
  end if;

  v_vat := public._customer_vat_rate(v_uid);
  v_sub := v_pkg.credits * v_pkg.unit_price;
  v_vat_amt := round(v_sub * v_vat / 100, 2);
  v_id := 'TP' || to_char(now() at time zone 'Asia/Bangkok', 'YYMMDD') || '-' || lpad(nextval('public.topup_seq')::text, 4, '0');

  insert into public.topup_requests (id, user_id, package_id, credits, unit_price, subtotal, vat_amount, total, slip_path, product, vat_rate)
  values (v_id, v_uid, v_pkg.id, v_pkg.credits, v_pkg.unit_price, v_sub, v_vat_amt, v_sub + v_vat_amt, p_slip_path, v_pkg.product, v_vat);

  return jsonb_build_object('id', v_id, 'credits', v_pkg.credits, 'subtotal', v_sub, 'vat_amount', v_vat_amt, 'total', v_sub + v_vat_amt,
                            'product', v_pkg.product, 'vat_rate', v_vat);
end $$;
