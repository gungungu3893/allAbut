create or replace function public._trg_block_staff_account()
returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from public.profiles p where p.id = new.user_id and p.account_type = 'staff') then
    raise exception 'STAFF_ACCOUNT';
  end if;
  return new;
end $$;
revoke all on function public._trg_block_staff_account() from public, anon, authenticated;
