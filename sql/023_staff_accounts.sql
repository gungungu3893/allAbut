-- 거래처 주문 (읽기 전용): 주문번호 · 치과명 · 접수일 · 단계 · 납품일 · 치아 수 (어버트먼트 n · 세트 n) + 단계 타임라인(종류 · 날짜만)
--   p_stage: 'active' (진행 중) | 'done' (완료 · 취소) | null (전부), p_from · p_to = 접수일(방콕)
