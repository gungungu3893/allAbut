create or replace function public._staff_token_hash(p_token text)
returns text language sql immutable as $$
  select encode(sha256(convert_to(coalesce(p_token, ''), 'UTF8')), 'hex');
$$;
revoke all on function public._staff_token_hash(text) from public, anon, authenticated;

-- 추측할 수 없는 토큰: 무작위 UUID 3개(122비트씩 = 366비트, 46바이트 이상) → 16진수 96글자
create or replace function public._staff_new_token()
returns text language sql volatile as $$
  select replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', '');
$$;
revoke all on function public._staff_new_token() from public, anon, authenticated;


-- ================================================================
-- 4) 프로필 트리거: 계정 종류 · 초대 링크 가입 (다른 프로필 트리거보다 먼저 — 이름이 trg_profile_account)
-- ================================================================
create or replace function public._trg_profile_account()
returns trigger
language plpgsql security definer set search_path = public, auth as $$
declare
  v_meta jsonb;
  v_created timestamptz;
  v_token text;
  inv public.staff_invites;
begin
  if tg_op = 'UPDATE' then
    -- 계정 종류는 고객 · 직원이 직접 못 바꿔요 (대표의 전환 함수만 allabut.staff_ok)
    if coalesce(current_setting('allabut.staff_ok', true), '') <> '1' then new.account_type := old.account_type; end if;
    return new;
  end if;

  -- INSERT: 기본은 고객. 초대 토큰이 있으면 검증해서 직원으로 (브라우저가 보낸 account_type · 역할은 안 믿어요)
  new.account_type := 'customer';
  select raw_user_meta_data, created_at into v_meta, v_created from auth.users where id = new.id;
  v_token := nullif(trim(coalesce(v_meta ->> 'staff_invite', '')), '');
  if v_token is null then return new; end if;

  -- 같은 링크로 두 명이 동시에 가입해도 한 명만 (행 잠금)
  select * into inv from public.staff_invites where token_hash = public._staff_token_hash(v_token) for update;
  if not found or inv.used_at is not null or inv.revoked_at is not null
     or inv.expires_at <= coalesce(v_created, now()) then   -- 만료 전에 가입(이메일 인증은 나중이어도 돼요)
    raise exception 'INVITE_INVALID';
  end if;
  if exists (select 1 from public.admins where user_id = new.id) then raise exception 'INVITE_INVALID'; end if;

  new.account_type := 'staff';
  insert into public.admins (user_id, role, display_name, added_by, active, pending_confirm, invite_id)
  values (new.id, inv.role, left(trim(coalesce(new.full_name, new.nickname, '')), 60), inv.created_by, true, inv.role = 'manager', inv.id);
  if inv.role = 'sales' then
    insert into public.sales_reps (user_id, active) values (new.id, true)
    on conflict (user_id) do update set active = true;
  end if;
  update public.staff_invites set used_by = new.id, used_at = now() where id = inv.id;
  -- 작업 기록 (가입한 사람이 처리한 일로 남아요)
  insert into public.admin_audit_log (actor_id, actor_name, action, target_type, target_id, detail)
  values (new.id, left(trim(coalesce(new.full_name, new.nickname, '')), 60), 'staff_joined', 'member', new.id::text,
          jsonb_build_object('role', inv.role, 'invite_id', inv.id, 'name', trim(coalesce(new.full_name, new.nickname, '')),
                             'pending', inv.role = 'manager'));
  return new;
end $$;
revoke all on function public._trg_profile_account() from public, anon, authenticated;
drop trigger if exists trg_profile_account on public.profiles;
create trigger trg_profile_account before insert or update on public.profiles
  for each row execute function public._trg_profile_account();


