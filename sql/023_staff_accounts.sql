-- ================================================================
-- 9) 직원 계정 빼기 (가장 최신 정의 + 직원 제외)
-- ================================================================
-- 의심 배지 (010 정의 + 직원 계정은 비교 대상 · 대상 아님 — 같은 사무실 IP · 기기로 고객이 의심받지 않게)
create or replace function public._suspicion_flags(p_user uuid)
returns text[]
language plpgsql stable security definer set search_path = public as $$
declare
  p record;
  f text[] := '{}';
begin
  select * into p from public.profiles where id = p_user;
  if p is null or p.account_type = 'staff' then return f; end if;   -- 직원 계정은 의심 배지 대상이 아니에요
  if coalesce(p.signup_ip, '') <> '' and exists (select 1 from public.profiles o where o.id <> p.id and o.account_type <> 'staff' and o.signup_ip = p.signup_ip) then
    f := array_append(f, 'same_ip'); end if;
  if coalesce(p.signup_device_id, '') <> '' and exists (select 1 from public.profiles o where o.id <> p.id and o.account_type <> 'staff' and o.signup_device_id = p.signup_device_id) then
    f := array_append(f, 'same_device'); end if;
  if public._norm_clinic(p.clinic_name) <> '' and exists (select 1 from public.profiles o where o.id <> p.id and o.account_type <> 'staff' and public._norm_clinic(o.clinic_name) = public._norm_clinic(p.clinic_name)) then
    f := array_append(f, 'similar_clinic'); end if;
  if public._norm_addr(p.address) <> '' and exists (select 1 from public.profiles o where o.id <> p.id and o.account_type <> 'staff'
       and (public._norm_addr(o.address) = public._norm_addr(p.address) or coalesce(o.reg_addr_norm, '') = public._norm_addr(p.address))) then
    f := array_append(f, 'same_address'); end if;
  if public._norm_name(p.full_name) <> '' and exists (select 1 from public.profiles o where o.id <> p.id and o.account_type <> 'staff' and public._norm_name(o.full_name) = public._norm_name(p.full_name)) then
    f := array_append(f, 'same_name'); end if;
  if coalesce(p.tax_id, '') <> '' and exists (select 1 from public.profiles o where o.id <> p.id and o.account_type <> 'staff' and o.tax_id = p.tax_id) then
    f := array_append(f, 'same_tax_id'); end if;
  return f;
end $$;
