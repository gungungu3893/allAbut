returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_rep uuid := public._my_rep_or_raise();
  v_y integer := extract(year from now() at time zone 'Asia/Bangkok')::int;
  v_m integer := extract(month from now() at time zone 'Asia/Bangkok')::int;
  v_r jsonb;
begin
  v_r := public._commission_month_json(v_y, v_m, v_rep) -> 'reps' -> 0;
  return jsonb_build_object(
    'year', v_y, 'month', v_m,
    'amount', coalesce((v_r ->> 'amount')::numeric, 0),
    'payments', coalesce((v_r ->> 'payments')::int, 0),
    'commission', coalesce((v_r ->> 'commission')::numeric, 0),
    'clients', (select count(*) from public.profiles p where p.sales_rep_id = v_rep and p.account_type <> 'staff'),
    'active_orders', (select count(*) from public.cnc_orders o join public.profiles p on p.id = o.user_id
                       where p.sales_rep_id = v_rep and p.account_type <> 'staff' and o.stage not in ('done', 'cancelled')),
    'pending_topups', (select count(*) from public.topup_requests t join public.profiles p on p.id = t.user_id
                        where p.sales_rep_id = v_rep and t.status = 'pending'),
    'recent', coalesce((
      select jsonb_agg(x order by (x ->> 'at')::timestamptz desc)
        from (
          (select jsonb_build_object('kind', 'order', 'id', o.id, 'customer', public._customer_label(o.user_id), 'at', o.created_at,
                                     'teeth', o.teeth_count) as x
             from public.cnc_orders o join public.profiles p on p.id = o.user_id
            where p.sales_rep_id = v_rep and p.account_type <> 'staff'
            order by o.created_at desc limit 10)
          union all
          (select jsonb_build_object('kind', 'payment', 'id', t.id, 'customer', public._customer_label(t.user_id), 'at', t.reviewed_at,
                                     'amount', t.subtotal)
             from public.topup_requests t
            where t.sales_rep_id = v_rep and t.status = 'approved'
            order by t.reviewed_at desc limit 10)
        ) s), '[]'::jsonb));
end $$;

-- 내 거래처: 치과명 · 담당자 이름 · 전화 · 지역(주소 앞부분) · 가입일 · 최근 주문일 · 최근 입금일 · 이번 달 입금액 · 잔액(종류별 숫자만)
