begin
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', o.id, 'client_id', o.user_id, 'customer', public._customer_label(o.user_id), 'created_at', o.created_at,
             'stage', o.stage, 'deadline', o.deadline, 'teeth', coalesce(o.teeth_count, 0),
             'crown_set', coalesce(o.crown_set_count, 0), 'abutment', greatest(coalesce(o.teeth_count, 0) - coalesce(o.crown_set_count, 0), 0),
             'timeline', coalesce((select jsonb_agg(jsonb_build_object('action', e ->> 'action', 'date', e ->> 'date'))
                                     from jsonb_array_elements(case when jsonb_typeof(o.review_history) = 'array' then o.review_history else '[]'::jsonb end) e
                                    where coalesce(e ->> 'action', '') <> '' and e ->> 'action' not in ('rep_changed')), '[]'::jsonb))
           order by o.created_at desc)
      from (select o.* from public.cnc_orders o join public.profiles p on p.id = o.user_id
             where p.sales_rep_id = v_rep and p.account_type <> 'staff'
               and (p_from is null or (o.created_at at time zone 'Asia/Bangkok')::date >= p_from)
               and (p_to is null or (o.created_at at time zone 'Asia/Bangkok')::date <= p_to)
               and (p_stage is null or (p_stage = 'active' and o.stage not in ('done', 'cancelled'))
                                    or (p_stage = 'done' and o.stage in ('done', 'cancelled')))
             order by o.created_at desc limit 500) o), '[]'::jsonb);
