create or replace function public.admin_role()
returns text
language sql stable security definer set search_path = public as $$
  select role from public.admins where user_id = auth.uid() and active and not pending_confirm;
$$;

create or replace function public.has_admin_role(p_min text)
returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select public._admin_role_rank(role) from public.admins
                    where user_id = auth.uid() and active and not pending_confirm), 0)
         >= greatest(public._admin_role_rank(p_min), 1);
$$;

create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid() and role in ('owner', 'manager', 'staff')
                  and active and not pending_confirm);
$$;

create or replace function public.is_sales_rep()
returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.sales_reps r join public.admins a on a.user_id = r.user_id
     where r.user_id = auth.uid() and r.active and a.active and not a.pending_confirm);
$$;

-- 내 역할 · 상태: status 'active' | 'pending'(대표 확인 전) | 'suspended'(정지) + account_type
create or replace function public.admin_me()
returns jsonb
language sql stable security definer set search_path = public as $$
  select case when a.user_id is null then null
              else jsonb_build_object('role', a.role, 'name', public._admin_name(a.user_id),
                                      'sales_rep', public.is_sales_rep(),
                                      'status', case when not a.active then 'suspended' when a.pending_confirm then 'pending' else 'active' end,
                                      'account_type', coalesce((select p.account_type from public.profiles p where p.id = a.user_id), 'customer')) end
    from (select auth.uid() as uid) me
    left join public.admins a on a.user_id = me.uid;
$$;

