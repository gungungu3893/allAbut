-- 정지 / 다시 켜기. 정지하는 영업의 거래처: p_move_to 가 있으면 그 영업에게, 없으면 담당 없음
create or replace function public.admin_set_member_active(p_user uuid, p_active boolean, p_move_to uuid default null)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  a public.admins;
  v_moved integer := 0;
  v_ids uuid[];
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if p_user = auth.uid() then raise exception 'CANNOT_CHANGE_SELF'; end if;
  select * into a from public.admins where user_id = p_user for update;
  if not found then raise exception 'NOT_MEMBER'; end if;
  if a.active = coalesce(p_active, false) then return jsonb_build_object('changed', false, 'moved', 0); end if;
  if not coalesce(p_active, false) then
    if a.role = 'owner' and (select count(*) from public.admins where role = 'owner' and active) <= 1 then raise exception 'LAST_OWNER'; end if;
    if p_move_to = p_user then raise exception 'REP_NOT_FOUND'; end if;
    select array_agg(id) into v_ids from public.profiles where sales_rep_id = p_user;
    if v_ids is not null then v_moved := public._move_clients(v_ids, p_move_to); end if;
  end if;
  update public.admins set active = coalesce(p_active, false) where user_id = p_user;
  perform public._audit(case when coalesce(p_active, false) then 'staff_reactivated' else 'staff_suspended' end, 'member', p_user::text,
    jsonb_build_object('name', public._admin_name(p_user), 'role', a.role, 'moved', v_moved,
                       'to_name', case when p_move_to is null then '' else public._admin_name(p_move_to) end));
  return jsonb_build_object('changed', true, 'moved', v_moved);
end $$;

-- 기존 팀원(고객으로 가입한 manager · staff · sales)을 직원 계정으로 — 크레딧 잔액 · 진행 중 주문이 있으면 막아요
create or replace function public.admin_convert_to_staff(p_user uuid)
returns void
language plpgsql security definer set search_path = public as $$
declare v_role text;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  select role into v_role from public.admins where user_id = p_user;
  if v_role is null then raise exception 'NOT_MEMBER'; end if;
  if v_role = 'owner' then raise exception 'INVALID_ROLE'; end if;   -- owner 는 고객 기능도 쓰니까 customer 그대로
  if exists (select 1 from public.profiles where id = p_user and account_type = 'staff') then return; end if;
  if exists (select 1 from public.credit_wallets w where w.user_id = p_user
              and (coalesce(w.balance, 0) > 0 or coalesce(w.balance_crown_set, 0) > 0)) then
    raise exception 'HAS_CREDITS';
  end if;
  if exists (select 1 from public.cnc_orders o where o.user_id = p_user and o.stage not in ('done', 'cancelled')) then
    raise exception 'HAS_ACTIVE_ORDERS';
  end if;
  if exists (select 1 from public.topup_requests t where t.user_id = p_user and t.status = 'pending') then
    raise exception 'HAS_ACTIVE_ORDERS';
  end if;
  perform set_config('allabut.staff_ok', '1', true);
  perform set_config('allabut.rep_ok', '1', true);
  update public.profiles set account_type = 'staff', sales_rep_id = null where id = p_user;
  perform set_config('allabut.staff_ok', '0', true);
  perform set_config('allabut.rep_ok', '0', true);
  perform public._audit('staff_converted', 'member', p_user::text, jsonb_build_object('name', public._admin_name(p_user), 'role', v_role));
end $$;

-- 역할 변경 (015 정의 + 자기 자신 변경 금지 + 영업으로 바꾸면 영업 담당 켜기)
create or replace function public.admin_set_role(p_user uuid, p_role text)
returns void
language plpgsql security definer set search_path = public as $$
declare v_old text;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if p_role not in ('owner', 'manager', 'staff', 'sales') then raise exception 'INVALID_ROLE'; end if;
  if p_user = auth.uid() then raise exception 'CANNOT_CHANGE_SELF'; end if;
  select role into v_old from public.admins where user_id = p_user for update;
  if v_old is null then raise exception 'NOT_MEMBER'; end if;
  if v_old = p_role then return; end if;
  if v_old = 'owner' and (select count(*) from public.admins where role = 'owner') <= 1 then
    raise exception 'LAST_OWNER';
  end if;
  update public.admins set role = p_role where user_id = p_user;
  if p_role = 'sales' then
    insert into public.sales_reps (user_id, active) values (p_user, true)
    on conflict (user_id) do update set active = true;
  end if;
  perform public._audit('team_role', 'member', p_user::text,
    jsonb_build_object('from', v_old, 'to', p_role, 'name', public._admin_name(p_user)));
end $$;

