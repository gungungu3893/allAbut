-- 내 월별 매출 (최근 n달, 기본 12): 입금 승인 금액(VAT 제외) · 건수 · 환불(VAT 제외) · 환불 차감 · 커미션 (커미션 탭과 같은 계산)
create or replace function public.sales_my_revenue(p_months integer default 12)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_rep uuid := public._my_rep_or_raise();
  v_n integer := greatest(1, least(coalesce(p_months, 12), 24));
  v_y integer := extract(year from now() at time zone 'Asia/Bangkok')::int;
  v_m integer := extract(month from now() at time zone 'Asia/Bangkok')::int;
  v_out jsonb := '[]'::jsonb;
  v_r jsonb;
  i integer;
  y integer;
  m integer;
begin
  for i in reverse (v_n - 1)..0 loop
    y := v_y + floor(((v_m - 1) - i)::numeric / 12)::int;
    m := (((v_m - 1 - i) % 12) + 12) % 12 + 1;
    v_r := public._commission_month_json(y, m, v_rep) -> 'reps' -> 0;
    v_out := v_out || jsonb_build_array(jsonb_build_object(
      'year', y, 'month', m,
      'amount', coalesce((v_r ->> 'amount')::numeric, 0),
      'payments', coalesce((v_r ->> 'payments')::int, 0),
      'refunds', coalesce((v_r ->> 'refunds')::int, 0),
      'refund_amount', coalesce((select sum((x ->> 'subtotal')::numeric) from jsonb_array_elements(coalesce(v_r -> 'items', '[]'::jsonb)) x
                                  where x ->> 'kind' = 'refund'), 0),
      'refund_deduction', coalesce((v_r ->> 'refund_deduction')::numeric, 0),
      'commission', coalesce((v_r ->> 'commission')::numeric, 0)));
  end loop;
  return v_out;
end $$;

