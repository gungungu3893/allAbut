create or replace function public.admin_create_staff_invite(p_role text, p_hours integer default 48, p_note text default '')
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_token text := public._staff_new_token();
  v_hours integer := coalesce(p_hours, 48);
  v_id bigint;
  v_exp timestamptz;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if p_role is null or p_role not in ('sales', 'staff', 'manager') then raise exception 'INVALID_ROLE'; end if;
  if v_hours < 1 or v_hours > 168 then raise exception 'INVALID_HOURS'; end if;
  v_exp := now() + make_interval(hours => v_hours);
  insert into public.staff_invites (token_hash, role, note, expires_at, created_by)
  values (public._staff_token_hash(v_token), p_role, left(trim(coalesce(p_note, '')), 100), v_exp, auth.uid())
  returning id into v_id;
  perform public._audit('staff_invite_created', 'invite', v_id::text,
    jsonb_build_object('role', p_role, 'hours', v_hours, 'note', left(trim(coalesce(p_note, '')), 100)));
  -- 원문 토큰은 이때 한 번만 돌려줘요 (DB 에는 sha256 만)
  return jsonb_build_object('id', v_id, 'token', v_token, 'role', p_role, 'expires_at', v_exp, 'hours', v_hours);
end $$;

create or replace function public._staff_invite_status(i public.staff_invites)
returns text language sql stable as $$
  select case when i.used_at is not null then 'used' when i.revoked_at is not null then 'revoked'
              when i.expires_at <= now() then 'expired' else 'waiting' end;
$$;
revoke all on function public._staff_invite_status(public.staff_invites) from public, anon, authenticated;

create or replace function public.admin_list_staff_invites()
returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', i.id, 'role', i.role, 'note', i.note, 'created_at', i.created_at, 'expires_at', i.expires_at,
             'created_by_name', case when i.created_by is null then '' else public._admin_name(i.created_by) end,
             'used_at', i.used_at, 'used_by', i.used_by,
             'used_by_name', case when i.used_by is null then '' else public._admin_name(i.used_by) end,
             'revoked_at', i.revoked_at, 'status', public._staff_invite_status(i))
           order by i.created_at desc)
      from (select * from public.staff_invites order by created_at desc limit 100) i), '[]'::jsonb);
end $$;

create or replace function public.admin_revoke_staff_invite(p_id bigint)
returns void
language plpgsql security definer set search_path = public as $$
declare i public.staff_invites;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  select * into i from public.staff_invites where id = p_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if public._staff_invite_status(i) <> 'waiting' then raise exception 'INVITE_INVALID'; end if;
  update public.staff_invites set revoked_at = now() where id = p_id;
  perform public._audit('staff_invite_revoked', 'invite', p_id::text, jsonb_build_object('role', i.role, 'note', i.note));
end $$;

-- 로그인 전 (가입 화면): 쓸 수 있는 링크인지 + 역할 이름만 (만든 사람 · 메모는 안 보여요)
create or replace function public.check_staff_invite(p_token text)
returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select jsonb_build_object('valid', true, 'role', i.role)
       from public.staff_invites i
      where i.token_hash = public._staff_token_hash(p_token)
        and length(coalesce(p_token, '')) >= 64
        and i.used_at is null and i.revoked_at is null and i.expires_at > now()),
    jsonb_build_object('valid', false, 'role', null));
$$;

revoke all on function public.admin_create_staff_invite(text, integer, text) from public, anon;
revoke all on function public.admin_list_staff_invites() from public, anon;
revoke all on function public.admin_revoke_staff_invite(bigint) from public, anon;
revoke all on function public.check_staff_invite(text) from public;
grant execute on function public.admin_create_staff_invite(text, integer, text) to authenticated;
grant execute on function public.admin_list_staff_invites() to authenticated;
grant execute on function public.admin_revoke_staff_invite(bigint) to authenticated;
grant execute on function public.check_staff_invite(text) to anon, authenticated;


