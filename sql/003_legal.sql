-- ================================================================
-- 1) 회사 정보 (1행)
-- ================================================================
create table if not exists public.company_settings (
  id            integer primary key default 1 check (id = 1),
  company_name  text not null default '',
  address       text not null default '',
  tax_id        text not null default '',
  email         text not null default '',
  phone         text not null default '',
  line_id       text not null default '',
  dpo_email     text not null default '',     -- 개인정보 담당 이메일 (PDPA 요청 접수)
  updated_at    timestamptz not null default now()
);
alter table public.company_settings enable row level security;
insert into public.company_settings (id) values (1) on conflict (id) do nothing;

drop policy if exists "company_settings: read all"     on public.company_settings;
drop policy if exists "company_settings: admin update" on public.company_settings;
create policy "company_settings: read all" on public.company_settings
  for select to anon, authenticated using (true);
create policy "company_settings: admin update" on public.company_settings
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
grant select on public.company_settings to anon, authenticated;
grant update on public.company_settings to authenticated;


-- ================================================================
-- 2) 법적 문서 버전
-- ================================================================
create table if not exists public.legal_versions (
  id              bigint generated by default as identity primary key,
  doc             text not null check (doc in ('terms', 'privacy', 'credit')),
  version         text not null check (length(trim(version)) between 1 and 40),
  effective_date  date not null default current_date,
  created_at      timestamptz not null default now(),
  constraint legal_versions_doc_version_key unique (doc, version)
);
create index if not exists idx_legal_versions_doc on public.legal_versions (doc, effective_date desc, created_at desc);
alter table public.legal_versions enable row level security;

drop policy if exists "legal_versions: read all"     on public.legal_versions;
drop policy if exists "legal_versions: admin insert" on public.legal_versions;
create policy "legal_versions: read all" on public.legal_versions
  for select to anon, authenticated using (true);
create policy "legal_versions: admin insert" on public.legal_versions
  for insert to authenticated with check (public.is_admin());
grant select on public.legal_versions to anon, authenticated;
grant insert on public.legal_versions to authenticated;

-- 첫 버전 3개 (오늘 날짜, 이미 문서별 버전이 있으면 건너뛰기)
insert into public.legal_versions (doc, version, effective_date)
select d, to_char(now() at time zone 'Asia/Bangkok', 'YYYY-MM-DD'), (now() at time zone 'Asia/Bangkok')::date
  from unnest(array['terms', 'privacy', 'credit']) d
 where not exists (select 1 from public.legal_versions v where v.doc = d);

-- 문서별 최신 버전 (시행일 → 등록 순서로 가장 나중 것)
create or replace function public.latest_legal_version(p_doc text)
returns text
language sql stable security definer set search_path = public as $$
  select version from public.legal_versions where doc = p_doc
   order by effective_date desc, created_at desc, id desc limit 1;
$$;


-- ================================================================
-- 3) 동의 기록 (profiles)
-- ================================================================
alter table public.profiles add column if not exists terms_version   text;
alter table public.profiles add column if not exists privacy_version text;
alter table public.profiles add column if not exists accepted_at     timestamptz;

-- 본인 동의: 지금 최신 버전과 같을 때만 기록 (오래된 버전으로 동의하는 것을 막아요)
create or replace function public.accept_legal(p_terms_version text, p_privacy_version text)
returns timestamptz
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_now timestamptz := now();
begin
  if v_uid is null then raise exception 'NOT_LOGGED_IN'; end if;
  if p_terms_version is distinct from public.latest_legal_version('terms')
     or p_privacy_version is distinct from public.latest_legal_version('privacy') then
    raise exception 'VERSION_OUTDATED';
  end if;
  update public.profiles
     set terms_version = p_terms_version, privacy_version = p_privacy_version, accepted_at = v_now
   where id = v_uid;
  if not found then raise exception 'NOT_FOUND'; end if;
  return v_now;
end $$;


-- ================================================================
-- 4) 계정 삭제 요청
-- ================================================================
create table if not exists public.account_deletion_requests (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.profiles(id) on delete cascade,
  reason      text not null default '',
  status      text not null default 'pending' check (status in ('pending', 'done', 'rejected')),
  admin_note  text,
  created_at  timestamptz not null default now(),
  handled_at  timestamptz
);
create index if not exists idx_account_deletion_status on public.account_deletion_requests (status, created_at desc);
alter table public.account_deletion_requests enable row level security;

drop policy if exists "deletion: read own" on public.account_deletion_requests;
create policy "deletion: read own" on public.account_deletion_requests
  for select to authenticated using (user_id = auth.uid() or public.is_admin());
grant select on public.account_deletion_requests to authenticated;
-- 쓰기는 아래 함수로만

-- 삭제 요청. 이미 대기 중이면 그 요청을 돌려줘요.
-- 돌려주는 값: { id, status, already, active_orders, balance }
--   active_orders > 0 이거나 balance > 0 이면 화면에서 "진행 중 주문·남은 크레딧 처리 후 진행" 안내
create or replace function public.request_account_deletion(p_reason text default '')
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_id bigint;
  v_already boolean := false;
  v_active integer;
  v_balance integer;
begin
  if v_uid is null then raise exception 'NOT_LOGGED_IN'; end if;

  select id into v_id from public.account_deletion_requests
   where user_id = v_uid and status = 'pending' order by created_at desc limit 1;
  if v_id is not null then
    v_already := true;
  else
    insert into public.account_deletion_requests (user_id, reason)
    values (v_uid, left(coalesce(trim(p_reason), ''), 1000))
    returning id into v_id;
  end if;

  select count(*) into v_active from public.cnc_orders where user_id = v_uid and stage not in ('done', 'cancelled');
  select coalesce(balance, 0) into v_balance from public.credit_wallets where user_id = v_uid;

  return jsonb_build_object('id', v_id, 'status', 'pending', 'already', v_already,
                            'active_orders', v_active, 'balance', coalesce(v_balance, 0));
end $$;

-- 관리자: 처리 완료 / 거절 (실제 계정 삭제는 진행 중 주문·크레딧·세무 기록을 확인한 뒤 대시보드에서 직접)
create or replace function public.admin_handle_deletion_request(p_id bigint, p_status text, p_note text default '')
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  if p_status not in ('done', 'rejected') then raise exception 'INVALID_ACTION'; end if;
  update public.account_deletion_requests
     set status = p_status, admin_note = nullif(trim(coalesce(p_note, '')), ''), handled_at = now()
   where id = p_id and status = 'pending';
  if not found then raise exception 'ALREADY_REVIEWED'; end if;
end $$;


-- ================================================================
-- 5) 실행 권한
-- ================================================================
revoke all on function public.latest_legal_version(text) from public;
grant execute on function public.latest_legal_version(text) to anon, authenticated;

revoke all on function public.accept_legal(text, text) from public, anon;
revoke all on function public.request_account_deletion(text) from public, anon;
revoke all on function public.admin_handle_deletion_request(bigint, text, text) from public, anon;
grant execute on function public.accept_legal(text, text) to authenticated;
grant execute on function public.request_account_deletion(text) to authenticated;
grant execute on function public.admin_handle_deletion_request(bigint, text, text) to authenticated;
