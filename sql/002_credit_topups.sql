-- 충전 요청 (가격은 DB 의 패키지·VAT 로 계산. 브라우저가 보낸 금액은 받지 않아요)
create or replace function public.create_topup_request(p_package_id bigint, p_slip_path text)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_pkg record;
  v_vat numeric;
  v_sub numeric;
  v_vat_amt numeric;
  v_id text;
begin
  if v_uid is null then raise exception 'NOT_LOGGED_IN'; end if;
  select * into v_pkg from public.credit_packages where id = p_package_id and active;
  if not found then raise exception 'PACKAGE_NOT_FOUND'; end if;

  -- 슬립 파일은 본인 폴더에 실제로 올라가 있어야 해요
  if p_slip_path is null or split_part(p_slip_path, '/', 1) <> v_uid::text or p_slip_path like '%..%' or length(p_slip_path) > 300 then
    raise exception 'SLIP_INVALID';
  end if;
  if not exists (select 1 from storage.objects where bucket_id = 'topup-slips' and name = p_slip_path) then
    raise exception 'SLIP_NOT_FOUND';
  end if;
  if (select count(*) from public.topup_requests where user_id = v_uid and status = 'pending') >= 5 then
    raise exception 'TOO_MANY_PENDING';
  end if;

  v_vat := coalesce((select vat_rate from public.payment_settings where id = 1), 7);
  v_sub := v_pkg.credits * v_pkg.unit_price;
  v_vat_amt := round(v_sub * v_vat / 100, 2);
  v_id := 'TP' || to_char(now() at time zone 'Asia/Bangkok', 'YYMMDD') || '-' || lpad(nextval('public.topup_seq')::text, 4, '0');

  insert into public.topup_requests (id, user_id, package_id, credits, unit_price, subtotal, vat_amount, total, slip_path)
  values (v_id, v_uid, v_pkg.id, v_pkg.credits, v_pkg.unit_price, v_sub, v_vat_amt, v_sub + v_vat_amt, p_slip_path);

  return jsonb_build_object('id', v_id, 'credits', v_pkg.credits, 'subtotal', v_sub, 'vat_amount', v_vat_amt, 'total', v_sub + v_vat_amt);
end $$;

-- 내 충전 요청 취소 (확인 중일 때만)
create or replace function public.cancel_my_topup(p_id text)
returns void
language plpgsql security definer set search_path = public as $$
begin
  update public.topup_requests set status = 'cancelled'
   where id = p_id and user_id = auth.uid() and status = 'pending';
  if not found then raise exception 'NOT_CANCELLABLE'; end if;
end $$;

-- 내 크레딧 묶음 (남은 것만, 만료 빠른 순)
create or replace function public.get_my_credit_lots()
returns table (id uuid, source text, quantity integer, remaining integer, unit_price numeric, created_at timestamptz, expires_at timestamptz)
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'NOT_LOGGED_IN'; end if;
  perform public._credit_recalc(auth.uid());
  return query
    select l.id, l.source, l.quantity, l.remaining, l.unit_price, l.created_at, l.expires_at
      from public.credit_lots l
     where l.user_id = auth.uid() and l.remaining > 0 and l.expires_at > now()
     order by l.expires_at, l.created_at;
end $$;

-- 주문 만들기 + 크레딧 차감 (치아 1개 = 1크레딧, FIFO, 한 번에 처리) — 기존과 같은 이름·인자·반환값
create or replace function public.create_cnc_order(
  p_patient text, p_deadline date, p_clinic text, p_addr text,
  p_phone text, p_line_id text, p_cases jsonb
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_teeth integer;
  v_id text;
  v_balance integer;
begin
  if v_uid is null then raise exception 'NOT_LOGGED_IN'; end if;
  if coalesce(trim(p_clinic), '') = '' or coalesce(trim(p_addr), '') = '' or coalesce(trim(p_phone), '') = '' then
    raise exception 'DELIVERY_REQUIRED';
  end if;

  select coalesce(sum(jsonb_array_length(coalesce(c -> 'teeth', '[]'::jsonb))), 0)
    into v_teeth from jsonb_array_elements(coalesce(p_cases, '[]'::jsonb)) c;
  if v_teeth < 1 then raise exception 'NO_TEETH'; end if;

  -- 같은 사용자의 동시 주문을 줄 세우기 (지갑 행 잠금)
  insert into public.credit_wallets (user_id, balance) values (v_uid, 0) on conflict (user_id) do nothing;
  perform 1 from public.credit_wallets where user_id = v_uid for update;
  perform public._credit_expire_lots(v_uid);

  if coalesce((select sum(remaining) from public.credit_lots where user_id = v_uid and remaining > 0 and expires_at > now()), 0) < v_teeth then
    raise exception 'INSUFFICIENT_CREDITS';
  end if;

  v_id := 'CA' || to_char(now(), 'YYMMDD') || '-' || lpad(nextval('public.cnc_order_seq')::text, 4, '0');
  insert into public.cnc_orders (id, user_id, patient, deadline, clinic, addr, phone, line_id, cases, teeth_count, credits_used)
  values (v_id, v_uid, coalesce(p_patient, ''), p_deadline, p_clinic, p_addr, p_phone, coalesce(p_line_id, ''), p_cases, v_teeth, v_teeth);

  perform public._credit_take(v_uid, v_teeth, v_id);
  v_balance := public._credit_recalc(v_uid);
  insert into public.credit_history (user_id, amount, type, order_id, description)
  values (v_uid, -v_teeth, 'use', v_id, 'CNC order ' || v_id || ' (' || v_teeth || ' teeth)');

  return jsonb_build_object('id', v_id, 'teeth', v_teeth, 'balance', v_balance);
end $$;

-- 접수(submitted) 상태일 때만 취소 + 원래 묶음으로 복구 — 기존과 같은 이름·인자·반환값(잔액)
create or replace function public.cancel_my_cnc_order(p_id text) returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_credits integer;
  v_result jsonb;
begin
  if v_uid is null then raise exception 'NOT_LOGGED_IN'; end if;
  update public.cnc_orders set stage = 'cancelled', updated_at = now()
   where id = p_id and user_id = v_uid and stage = 'submitted'
   returning credits_used into v_credits;
  if not found then raise exception 'NOT_CANCELLABLE'; end if;

  v_result := public._credit_restore(p_id, v_uid, v_credits);
  perform public._credit_refund_history(v_uid, p_id, v_result, 'Cancel');
  return public._credit_recalc(v_uid);
end $$;


