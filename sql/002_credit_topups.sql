-- 처음 한 번 잔액 맞추기 (모든 지갑 = 남은 묶음 합계)
select public.expire_credit_lots();
update public.credit_wallets w
   set balance = coalesce((select sum(l.remaining) from public.credit_lots l where l.user_id = w.user_id and l.expires_at > now()), 0),
       updated_at = now()
 where w.balance <> coalesce((select sum(l.remaining) from public.credit_lots l where l.user_id = w.user_id and l.expires_at > now()), 0);
