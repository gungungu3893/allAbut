-- 만료된 묶음 처리: remaining → 0, 이력 'expire', 지갑 갱신. p_user 가 null 이면 전체
create or replace function public._credit_expire_lots(p_user uuid default null)
returns integer
language plpgsql security definer set search_path = public as $$
declare
  r record;
  v_count integer := 0;
  v_users uuid[] := '{}';
begin
  for r in
    select id, user_id, remaining, expires_at from public.credit_lots
     where remaining > 0 and expires_at <= now() and (p_user is null or user_id = p_user)
     order by expires_at
     for update
  loop
    update public.credit_lots set remaining = 0 where id = r.id;
    insert into public.credit_history (user_id, amount, type, description, lot_id)
    values (r.user_id, -r.remaining, 'expire',
            'Expired ' || r.remaining || ' credits (valid until ' || to_char(r.expires_at at time zone 'Asia/Bangkok', 'YYYY-MM-DD') || ')',
            r.id);
    v_count := v_count + 1;
    if not (r.user_id = any (v_users)) then v_users := v_users || r.user_id; end if;
  end loop;

  if array_length(v_users, 1) > 0 then
    insert into public.credit_wallets (user_id, balance)
    select u, 0 from unnest(v_users) u on conflict (user_id) do nothing;
    update public.credit_wallets w
       set balance = coalesce((select sum(l.remaining) from public.credit_lots l where l.user_id = w.user_id), 0),
           updated_at = now()
     where w.user_id = any (v_users);
  end if;
  return v_count;
end $$;

-- 지갑 잔액 = 남은 묶음 합계 (먼저 만료 처리)
create or replace function public._credit_recalc(p_user uuid)
returns integer
language plpgsql security definer set search_path = public as $$
declare v_balance integer;
begin
  perform public._credit_expire_lots(p_user);
  insert into public.credit_wallets (user_id, balance) values (p_user, 0) on conflict (user_id) do nothing;
  update public.credit_wallets
     set balance = coalesce((select sum(remaining) from public.credit_lots where user_id = p_user and expires_at > now()), 0),
         updated_at = now()
   where user_id = p_user
   returning balance into v_balance;
  return v_balance;
end $$;

-- 묶음에서 FIFO 로 빼기 (먼저 만료되는 묶음부터). p_order 가 있으면 주문별 사용 기록
create or replace function public._credit_take(p_user uuid, p_amount integer, p_order text default null)
returns void
language plpgsql security definer set search_path = public as $$
declare
  r record;
  v_need integer := p_amount;
  v_take integer;
  v_available integer;
begin
  if p_amount <= 0 then return; end if;
  select coalesce(sum(remaining), 0) into v_available
    from public.credit_lots where user_id = p_user and remaining > 0 and expires_at > now();
  if v_available < p_amount then raise exception 'INSUFFICIENT_CREDITS'; end if;

  for r in
    select id, remaining from public.credit_lots
     where user_id = p_user and remaining > 0 and expires_at > now()
     order by expires_at, created_at
     for update
  loop
    exit when v_need <= 0;
    v_take := least(r.remaining, v_need);
    update public.credit_lots set remaining = remaining - v_take where id = r.id;
    if p_order is not null then
      insert into public.credit_lot_usage (order_id, lot_id, quantity) values (p_order, r.id, v_take);
    end if;
    v_need := v_need - v_take;
  end loop;
  if v_need > 0 then raise exception 'INSUFFICIENT_CREDITS'; end if;
end $$;

-- 주문 취소: 사용한 묶음으로 되돌리기. 만료된 묶음 몫은 되돌리지 않아요.
-- 돌려주는 값: { restored, lost } — 묶음 기록이 없는 예전 주문은 새 'migration' 묶음(12개월)으로 돌려줘요
create or replace function public._credit_restore(p_order text, p_user uuid, p_credits integer)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  r record;
  v_restored integer := 0;
  v_lost integer := 0;
  v_any boolean := false;
begin
  for r in
    select u.id as usage_id, u.quantity, l.id as lot_id, l.expires_at
      from public.credit_lot_usage u join public.credit_lots l on l.id = u.lot_id
     where u.order_id = p_order and u.restored_at is null
     for update of u, l
  loop
    v_any := true;
    if r.expires_at > now() then
      update public.credit_lots set remaining = least(quantity, remaining + r.quantity) where id = r.lot_id;
      v_restored := v_restored + r.quantity;
    else
      v_lost := v_lost + r.quantity;
    end if;
    update public.credit_lot_usage set restored_at = now() where id = r.usage_id;
  end loop;

  if not v_any and coalesce(p_credits, 0) > 0
     and not exists (select 1 from public.credit_lot_usage where order_id = p_order) then
    insert into public.credit_lots (user_id, source, quantity, remaining, unit_price, expires_at)
    values (p_user, 'migration', p_credits, p_credits, 0, now() + interval '12 months');
    v_restored := p_credits;
  end if;
  return jsonb_build_object('restored', v_restored, 'lost', v_lost);
end $$;

-- 취소 환불 이력: 'refund' (사용했던 전체) + 만료돼서 못 돌려준 몫은 'expire'
create or replace function public._credit_refund_history(p_user uuid, p_order text, p_result jsonb, p_label text)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_restored integer := coalesce((p_result ->> 'restored')::int, 0);
  v_lost integer := coalesce((p_result ->> 'lost')::int, 0);
begin
  if v_restored + v_lost > 0 then
    insert into public.credit_history (user_id, amount, type, order_id, description)
    values (p_user, v_restored + v_lost, 'refund', p_order, p_label || ' ' || p_order);
  end if;
  if v_lost > 0 then
    insert into public.credit_history (user_id, amount, type, order_id, description)
    values (p_user, -v_lost, 'expire', p_order, 'Not restored: ' || v_lost || ' credits from an expired lot (' || p_order || ')');
  end if;
end $$;

-- 현금 환불 계산 (묶음별) — 내부용
create or replace function public._credit_refund_quote(p_user uuid)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  r record;
  v_vat numeric := coalesce((select vat_rate from public.payment_settings where id = 1), 7);
  v_single numeric := coalesce((select unit_price from public.credit_packages where credits = 1 order by active desc limit 1), 2200);
  v_paid numeric;
  v_used integer;
  v_refund numeric;
  v_rule text;
  v_lots jsonb := '[]'::jsonb;
  v_total numeric := 0;
begin
  for r in
    select l.*, t.total as topup_total
      from public.credit_lots l left join public.topup_requests t on t.id = l.topup_id
     where l.user_id = p_user and l.remaining > 0
     order by l.expires_at
  loop
    v_used := r.quantity - r.remaining;
    v_paid := coalesce(r.topup_total, round(r.quantity * r.unit_price * (1 + v_vat / 100), 2));
    v_refund := 0;
    if r.expires_at <= now() then
      v_rule := 'expired';
    elsif r.source <> 'purchase' or r.unit_price = 0 then
      v_rule := 'bonus';
    elsif r.created_at < now() - interval '14 days' then
      v_rule := 'over_14_days';
    elsif v_used = 0 then
      v_rule := 'full';
      v_refund := v_paid;
    else
      v_rule := 'recalculated';
      v_refund := greatest(0, round(v_paid - v_used * v_single * (1 + v_vat / 100), 2));
    end if;
    v_total := v_total + v_refund;
    v_lots := v_lots || jsonb_build_object(
      'lot_id', r.id, 'source', r.source, 'created_at', r.created_at, 'expires_at', r.expires_at,
      'quantity', r.quantity, 'remaining', r.remaining, 'used', v_used, 'unit_price', r.unit_price,
      'paid_total', v_paid, 'refundable', v_refund, 'rule', v_rule, 'topup_id', r.topup_id);
  end loop;
  return jsonb_build_object('lots', v_lots, 'total_refundable', v_total, 'single_price', v_single, 'vat_rate', v_vat);
end $$;


