-- 충전 승인: 묶음(12개월) + 이력 'charge' + 잔액 갱신. 같은 요청 두 번 승인 불가
create or replace function public.admin_approve_topup(p_id text)
returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_req record;
  v_lot uuid;
  v_exp timestamptz := now() + interval '12 months';
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  select * into v_req from public.topup_requests where id = p_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if v_req.status <> 'pending' then raise exception 'ALREADY_REVIEWED'; end if;

  insert into public.credit_lots (user_id, source, quantity, remaining, unit_price, topup_id, expires_at)
  values (v_req.user_id, 'purchase', v_req.credits, v_req.credits, v_req.unit_price, v_req.id, v_exp)
  returning id into v_lot;

  update public.topup_requests set status = 'approved', reviewed_by = auth.uid(), reviewed_at = now() where id = p_id;
  insert into public.credit_history (user_id, amount, type, description, lot_id)
  values (v_req.user_id, v_req.credits, 'charge',
          'Top-up ' || v_req.id || ' (valid until ' || to_char(v_exp at time zone 'Asia/Bangkok', 'YYYY-MM-DD') || ')', v_lot);
  return public._credit_recalc(v_req.user_id);
end $$;

-- 충전 거절 (사유 필수)
create or replace function public.admin_reject_topup(p_id text, p_reason text)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'NOTE_REQUIRED'; end if;
  update public.topup_requests
     set status = 'rejected', reject_reason = trim(p_reason), reviewed_by = auth.uid(), reviewed_at = now()
   where id = p_id and status = 'pending';
  if not found then raise exception 'ALREADY_REVIEWED'; end if;
end $$;

-- 크레딧 지급(+) = 보너스 묶음(12개월, 단가 0) / 차감(-) = FIFO — 기존과 같은 이름·인자·반환값(잔액)
create or replace function public.admin_add_credits(p_user uuid, p_amount integer, p_description text default '')
returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_lot uuid;
  v_exp timestamptz := now() + interval '12 months';
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  if p_amount is null or p_amount = 0 then raise exception 'INVALID_AMOUNT'; end if;
  insert into public.credit_wallets (user_id, balance) values (p_user, 0) on conflict (user_id) do nothing;
  perform 1 from public.credit_wallets where user_id = p_user for update;

  if p_amount > 0 then
    insert into public.credit_lots (user_id, source, quantity, remaining, unit_price, expires_at)
    values (p_user, 'bonus', p_amount, p_amount, 0, v_exp) returning id into v_lot;
    insert into public.credit_history (user_id, amount, type, description, lot_id)
    values (p_user, p_amount, 'charge',
            coalesce(nullif(trim(p_description), ''), 'Bonus') || ' (valid until ' || to_char(v_exp at time zone 'Asia/Bangkok', 'YYYY-MM-DD') || ')', v_lot);
  else
    perform public._credit_expire_lots(p_user);
    begin
      perform public._credit_take(p_user, -p_amount, null);
    exception when others then
      raise exception 'BALANCE_NEGATIVE: not enough balance to deduct';
    end;
    insert into public.credit_history (user_id, amount, type, description)
    values (p_user, p_amount, 'adjust', coalesce(p_description, ''));
  end if;
  return public._credit_recalc(p_user);
end $$;

-- 관리자 취소 + 원래 묶음으로 복구 (가공 전 단계만). 이름이 같은 예전 함수는 모두 지우고 새로 만들어요
do $$
declare f record;
begin
  for f in
    select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public' and p.proname = 'admin_cancel_cnc_order'
  loop
    execute 'drop function ' || f.sig;
  end loop;
end $$;

create function public.admin_cancel_cnc_order(p_id text, p_reason text default '')
returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_order record;
  v_result jsonb;
  v_last jsonb;
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  select * into v_order from public.cnc_orders where id = p_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if v_order.stage not in ('submitted','confirmed','design_ready','design_revision','approved') then
    if v_order.stage in ('milling','shipped','done') then raise exception 'CANNOT_CANCEL_AFTER_MILLING'; end if;
    raise exception 'NOT_CANCELLABLE';
  end if;

  -- 앱이 미리 붙인 'admin_cancelled' 기록이 없으면 여기서 붙여요 (LINE 알림이 관리자 취소인지 구분하는 데 써요)
  v_last := v_order.review_history -> -1;
  update public.cnc_orders
     set stage = 'cancelled', updated_at = now(),
         review_history = case when coalesce(v_last ->> 'action', '') = 'admin_cancelled' then review_history
                               else review_history || jsonb_build_array(jsonb_build_object(
                                 'action', 'admin_cancelled', 'note', coalesce(p_reason, ''), 'date', now(), 'by', 'admin')) end
   where id = p_id;

  v_result := public._credit_restore(p_id, v_order.user_id, v_order.credits_used);
  perform public._credit_refund_history(v_order.user_id, p_id, v_result, 'Admin cancel');
  return public._credit_recalc(v_order.user_id);
end $$;

-- 현금 환불 계산 (계산만)
create or replace function public.admin_refund_quote(p_user uuid)
returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  perform public._credit_recalc(p_user);
  return public._credit_refund_quote(p_user);
end $$;

-- 현금 환불 기록: 고른 묶음 remaining → 0, 이력 'refund_cash'. 송금은 관리자가 따로 해요
create or replace function public.admin_refund_cash(p_user uuid, p_lot_ids uuid[], p_amount numeric, p_note text default '')
returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_quote jsonb;
  v_lot jsonb;
  v_max numeric := 0;
  v_credits integer := 0;
  v_count integer := 0;
begin
  if not public.is_admin() then raise exception 'NOT_ADMIN'; end if;
  if p_lot_ids is null or array_length(p_lot_ids, 1) is null then raise exception 'NO_LOTS'; end if;
  if p_amount is null or p_amount < 0 then raise exception 'INVALID_AMOUNT'; end if;

  perform public._credit_recalc(p_user);
  v_quote := public._credit_refund_quote(p_user);
  for v_lot in select * from jsonb_array_elements(v_quote -> 'lots') loop
    if (v_lot ->> 'lot_id')::uuid = any (p_lot_ids) then
      if (v_lot ->> 'rule') not in ('full', 'recalculated') then raise exception 'LOT_NOT_REFUNDABLE'; end if;
      v_max := v_max + (v_lot ->> 'refundable')::numeric;
      v_credits := v_credits + (v_lot ->> 'remaining')::int;
      v_count := v_count + 1;
    end if;
  end loop;
  if v_count <> array_length(p_lot_ids, 1) then raise exception 'LOT_NOT_REFUNDABLE'; end if;
  if p_amount > v_max + 0.005 then raise exception 'AMOUNT_TOO_HIGH'; end if;

  update public.credit_lots set remaining = 0 where user_id = p_user and id = any (p_lot_ids);
  insert into public.credit_history (user_id, amount, type, description)
  values (p_user, -v_credits, 'refund_cash',
          'Cash refund THB ' || to_char(p_amount, 'FM999,999,990.00') || coalesce(' · ' || nullif(trim(p_note), ''), ''));
  return public._credit_recalc(p_user);
end $$;


