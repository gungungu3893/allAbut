    return;
  end if;
  for j in select jobid from cron.job where jobname in ('allabut-expire-credits', 'allabut-expiry-reminders') loop
    perform cron.unschedule(j.jobid);
  end loop;
  perform cron.schedule('allabut-expire-credits',   '0 18 * * *', 'select public.expire_credit_lots()');
  perform cron.schedule('allabut-expiry-reminders', '5 18 * * *', 'select public.send_credit_expiry_reminders()');
