-- allAbut — 015: 영업직원(sales) 역할 · 주문별 담당자 · 직원별 커미션 요율 · 월별 커미션 정산
-- ================================================================
-- 1) 역할 'sales' (영업) — owner ⊃ manager ⊃ staff 계층과는 별개
--    · _admin_role_rank('sales') = 0 → has_admin_role('staff' 이상) 은 sales 에게 항상 false
--    · is_admin() 을 "owner · manager · staff 만" 으로 다시 정의 → is_admin() 을 쓰는 모든 읽기 규칙(RLS · 저장소 밖 규칙 포함)이 sales 에게 안 열려요
--    · is_sales_rep() / my_sales_rep_id()
-- 2) 영업 담당자 sales_reps (팀원 누구나 담당 가능: owner · manager · staff · sales), 요율 sales_rep_rates (percent | per_tooth, 적용 시작일)
--    profiles.sales_rep_id (고객 담당) · cnc_orders.sales_rep_id (주문 담당) · cnc_orders.shipped_at (배송 시각)
--    · 새 주문: insert 트리거가 고객의 담당자를 자동 복사 (create_cnc_order 는 그대로)
--    · 담당자는 관리자 함수로만 바뀌어요 (고객 · staff 가 표를 직접 고쳐도 트리거가 되돌림)
-- 3) 커미션 (방콕 달 기준, 그 달에 shipped 된 주문, cancelled 제외, 담당자 있는 것)
--    매출 = credit_lot_usage(restored_at 없음) × 묶음 unit_price (VAT 별도 — 매출 대시보드와 같은 규칙, 무료 묶음은 단가 0)
--    percent = 매출 × 값% / per_tooth = 유료 묶음으로 만든 치아 수 × 값 (THB), 소수 2자리 반올림
--    요율 = 배송일(방콕)에 유효한 것 (effective_from <= 배송일 중 가장 최근)
-- 4) 정산 잠금 commission_payouts (직원 · 연 · 월 스냅샷) — 잠긴 달은 스냅샷 숫자 그대로, 담당자 변경 불가(COMMISSION_LOCKED)
--
-- 실행 순서: 014 다음 (005 · 008 · 009 필요). 두 번 실행해도 안전.
-- 다시 정의하는 기존 함수 (전부 sql/005 의 가장 최신 정의 + 필요한 부분만):
--   is_admin · admin_me · admin_add_member · admin_set_role
--   → 005 를 다시 실행하면 015 도 다시 실행하세요 (is_admin 이 sales 에게 열리는 예전 모양으로 돌아가요)
-- 기존 SQL 파일은 고치지 않아요.


