create or replace function public.admin_add_member(p_email text, p_role text default 'staff', p_display_name text default '')
returns uuid
language plpgsql security definer set search_path = public, auth as $$
declare v_user uuid;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if p_role not in ('owner', 'manager', 'staff', 'sales') then raise exception 'INVALID_ROLE'; end if;
  select id into v_user from auth.users where lower(email) = lower(trim(coalesce(p_email, ''))) limit 1;
  if v_user is null then raise exception 'USER_NOT_FOUND'; end if;
  if exists (select 1 from public.admins where user_id = v_user) then raise exception 'ALREADY_MEMBER'; end if;
  insert into public.admins (user_id, role, display_name, added_by)
  values (v_user, p_role, left(trim(coalesce(p_display_name, '')), 60), auth.uid());
  perform public._audit('team_add', 'member', v_user::text,
    jsonb_build_object('email', lower(trim(p_email)), 'role', p_role, 'name', trim(coalesce(p_display_name, ''))));
  return v_user;
end $$;

create or replace function public.admin_set_role(p_user uuid, p_role text)
returns void
language plpgsql security definer set search_path = public as $$
declare v_old text;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if p_role not in ('owner', 'manager', 'staff', 'sales') then raise exception 'INVALID_ROLE'; end if;
  select role into v_old from public.admins where user_id = p_user for update;
  if v_old is null then raise exception 'NOT_MEMBER'; end if;
  if v_old = p_role then return; end if;
  if v_old = 'owner' and (select count(*) from public.admins where role = 'owner') <= 1 then
    raise exception 'LAST_OWNER';
  end if;
  update public.admins set role = p_role where user_id = p_user;
  perform public._audit('team_role', 'member', p_user::text,
    jsonb_build_object('from', v_old, 'to', p_role, 'name', public._admin_name(p_user)));
end $$;

-- 영업 담당 켜기 · 끄기 (owner) — 팀원만
create or replace function public.admin_set_sales_rep(p_user uuid, p_active boolean)
returns void
language plpgsql security definer set search_path = public as $$
declare v_old boolean;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if not exists (select 1 from public.admins where user_id = p_user) then raise exception 'NOT_MEMBER'; end if;
  select active into v_old from public.sales_reps where user_id = p_user;
  if v_old is not distinct from coalesce(p_active, false) then return; end if;
  if coalesce(p_active, false) then
    insert into public.sales_reps (user_id, active) values (p_user, true)
    on conflict (user_id) do update set active = true;
  else
    update public.sales_reps set active = false where user_id = p_user;
  end if;
  perform public._audit(case when coalesce(p_active, false) then 'sales_rep_on' else 'sales_rep_off' end,
    'member', p_user::text, jsonb_build_object('name', public._admin_name(p_user)));
end $$;

-- 영업 담당 목록 (staff 이상 — 이름 · 켜짐. 요율은 owner 에게만)
create or replace function public.admin_list_sales_reps()
returns jsonb
language plpgsql stable security definer set search_path = public, auth as $$
declare
  v_owner boolean := public.has_admin_role('owner');
  v_today date := (now() at time zone 'Asia/Bangkok')::date;
begin
  if not public.has_admin_role('staff') then raise exception 'NOT_ADMIN'; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'rep_id', r.user_id, 'name', public._admin_name(r.user_id), 'email', coalesce(u.email::text, ''),
             'role', coalesce(a.role, ''), 'active', r.active and a.user_id is not null,
             'rate', case when v_owner then (
                select jsonb_build_object('type', x.type, 'value', x.value, 'effective_from', x.effective_from)
                  from public.sales_rep_rates x
                 where x.rep_id = r.user_id and x.effective_from <= v_today
                 order by x.effective_from desc, x.created_at desc, x.id desc limit 1) end)
           order by (r.active and a.user_id is not null) desc, public._admin_name(r.user_id))
      from public.sales_reps r
      left join public.admins a on a.user_id = r.user_id
      left join auth.users u on u.id = r.user_id), '[]'::jsonb);
end $$;

-- 커미션 요율 추가 (owner) — 이력은 지우지 않아요. 같은 시작일이면 나중에 넣은 것이 이겨요
create or replace function public.admin_set_rep_rate(p_rep uuid, p_type text, p_value numeric, p_effective_from date default null)
returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_id bigint;
  v_from date := coalesce(p_effective_from, (now() at time zone 'Asia/Bangkok')::date);
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if not exists (select 1 from public.sales_reps where user_id = p_rep) then raise exception 'REP_NOT_FOUND'; end if;
  if p_type not in ('percent', 'per_tooth') then raise exception 'INVALID_RATE_TYPE'; end if;
  if p_value is null or p_value < 0 or (p_type = 'percent' and p_value > 100) or p_value > 1000000 then
    raise exception 'INVALID_RATE_VALUE';
  end if;
  insert into public.sales_rep_rates (rep_id, type, value, effective_from, created_by)
  values (p_rep, p_type, round(p_value, 2), v_from, auth.uid())
  returning id into v_id;
  perform public._audit('commission_rate', 'member', p_rep::text,
    jsonb_build_object('name', public._admin_name(p_rep), 'type', p_type, 'value', round(p_value, 2), 'effective_from', v_from));
  return v_id;
end $$;


-- ================================================================
-- 7) 담당자 지정 (manager 이상)
-- ================================================================
-- 이 주문이 지급 완료로 잠긴 달에 들어 있는지 (옛 담당 · 새 담당 · 스냅샷 안)
create or replace function public._order_commission_locked(p_order text, p_shipped timestamptz, p_old uuid, p_new uuid)
returns boolean
language sql stable security definer set search_path = public as $$
  select p_shipped is not null and exists (
    select 1 from public.commission_payouts c
     where c.year = extract(year from p_shipped at time zone 'Asia/Bangkok')::int
       and c.month = extract(month from p_shipped at time zone 'Asia/Bangkok')::int
       and (c.rep_id = p_old or c.rep_id = p_new
            or c.orders @> jsonb_build_array(jsonb_build_object('order_id', p_order))));
$$;

-- 주문 담당 바꾸기 (p_rep null = 담당 없음). 이미 담당이 있으면 사유 필수
-- review_history 에는 담당 id 만 (사유는 고객이 볼 수 있는 기록이라 넣지 않고 작업 기록에만)
create or replace function public.admin_set_order_rep(p_order text, p_rep uuid, p_reason text default '')
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_old uuid;
  v_shipped timestamptz;
  v_clinic text;
begin
  if not public.has_admin_role('manager') then raise exception 'NOT_ADMIN'; end if;
  select sales_rep_id, shipped_at, clinic into v_old, v_shipped, v_clinic
    from public.cnc_orders where id = p_order for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if p_rep is not null and not exists (select 1 from public.sales_reps where user_id = p_rep and active) then
    raise exception 'REP_NOT_FOUND';
  end if;
  if v_old is not distinct from p_rep then return jsonb_build_object('changed', false, 'rep_id', p_rep); end if;
  if v_old is not null and coalesce(trim(p_reason), '') = '' then raise exception 'REASON_REQUIRED'; end if;
  if public._order_commission_locked(p_order, v_shipped, v_old, p_rep) then raise exception 'COMMISSION_LOCKED'; end if;

  perform set_config('allabut.rep_ok', '1', true);
  update public.cnc_orders
     set sales_rep_id = p_rep, updated_at = now(),
         review_history = coalesce(review_history, '[]'::jsonb) || jsonb_build_array(
           jsonb_build_object('action', 'rep_changed', 'old_rep', v_old, 'new_rep', p_rep, 'date', now(), 'by', 'admin'))
   where id = p_order;
  perform set_config('allabut.rep_ok', '0', true);

  perform public._audit('order_rep', 'order', p_order, jsonb_build_object(
    'from', v_old, 'to', p_rep, 'clinic', v_clinic, 'reason', trim(coalesce(p_reason, '')),
    'from_name', case when v_old is null then '' else public._admin_name(v_old) end,
    'to_name', case when p_rep is null then '' else public._admin_name(p_rep) end));
  return jsonb_build_object('changed', true, 'rep_id', p_rep, 'old_rep', v_old);
end $$;

-- 고객 담당 바꾸기 (+ 아직 배송 전인 주문도 같이 바꿀지)
create or replace function public.admin_set_customer_rep(p_user uuid, p_rep uuid, p_apply_open_orders boolean default false)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_old uuid;
  v_n integer := 0;
  v_changed boolean;
begin
  if not public.has_admin_role('manager') then raise exception 'NOT_ADMIN'; end if;
  select sales_rep_id into v_old from public.profiles where id = p_user for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if p_rep is not null and not exists (select 1 from public.sales_reps where user_id = p_rep and active) then
    raise exception 'REP_NOT_FOUND';
  end if;
  v_changed := v_old is distinct from p_rep;

  perform set_config('allabut.rep_ok', '1', true);
  if v_changed then
    update public.profiles set sales_rep_id = p_rep where id = p_user;
  end if;
  if coalesce(p_apply_open_orders, false) then
    -- 배송 전 주문만 (배송된 주문은 커미션 달이 정해져서 주문마다 따로 바꿔요)
    update public.cnc_orders o
       set review_history = coalesce(o.review_history, '[]'::jsonb) || jsonb_build_array(
             jsonb_build_object('action', 'rep_changed', 'old_rep', o.sales_rep_id, 'new_rep', p_rep, 'date', now(), 'by', 'admin')),
           sales_rep_id = p_rep, updated_at = now()
     where o.user_id = p_user and o.stage not in ('shipped', 'done', 'cancelled')
       and o.sales_rep_id is distinct from p_rep;
    get diagnostics v_n = row_count;
  end if;
  perform set_config('allabut.rep_ok', '0', true);

  if v_changed or v_n > 0 then
    perform public._audit('customer_rep', 'customer', p_user::text, jsonb_build_object(
      'from', v_old, 'to', p_rep, 'open_orders', v_n,
      'from_name', case when v_old is null then '' else public._admin_name(v_old) end,
      'to_name', case when p_rep is null then '' else public._admin_name(p_rep) end));
  end if;
  return jsonb_build_object('changed', v_changed, 'rep_id', p_rep, 'orders_updated', v_n);
end $$;


-- ================================================================
-- 8) 커미션 계산
-- ================================================================
-- 그 달(방콕)에 배송된 주문 한 줄씩 (담당자 있는 것, cancelled 제외). p_rep 가 있으면 그 담당자만
create or replace function public._commission_rows(p_year integer, p_month integer, p_rep uuid default null)
returns table (order_id text, rep_id uuid, clinic text, shipped_at timestamptz, teeth integer, paid_teeth integer,
               revenue numeric, rate_type text, rate_value numeric, commission numeric)
language sql stable security definer set search_path = public as $$
  with o as (
    select o.id, o.sales_rep_id, o.clinic, o.shipped_at, o.teeth_count, o.credits_used, coalesce(o.bonus_used, 0) as bonus_used
      from public.cnc_orders o
     where o.sales_rep_id is not null and o.stage <> 'cancelled'
       and (p_rep is null or o.sales_rep_id = p_rep)
       and o.shipped_at >= public._bkk_month_start(p_year, p_month)
       and o.shipped_at <  public._bkk_month_end(p_year, p_month)
  ), u as (
    select cu.order_id,
           sum(cu.quantity * l.unit_price) as rev,
           sum(case when public._is_free_source(l.source) then 0 else cu.quantity end)::int as paid
      from public.credit_lot_usage cu join public.credit_lots l on l.id = cu.lot_id
     where cu.restored_at is null and cu.order_id in (select id from o)
     group by cu.order_id
  ), x as (
    select o.id, o.sales_rep_id, o.clinic, o.shipped_at, o.teeth_count,
           -- 묶음 기록이 없는 예전 주문: 크레딧 − 등록 주소 전용 무료
           coalesce(u.paid, greatest(o.credits_used - o.bonus_used, 0))::int as paid,
           round(coalesce(u.rev, 0), 2) as rev,
           rt.type as rtype, rt.value as rvalue
      from o
      left join u on u.order_id = o.id
      left join lateral (
        select r.type, r.value from public.sales_rep_rates r
         where r.rep_id = o.sales_rep_id and r.effective_from <= (o.shipped_at at time zone 'Asia/Bangkok')::date
         order by r.effective_from desc, r.created_at desc, r.id desc limit 1) rt on true
  )
  select x.id, x.sales_rep_id, x.clinic, x.shipped_at, x.teeth_count, x.paid, x.rev, x.rtype, x.rvalue,
         round(case x.rtype when 'percent' then x.rev * x.rvalue / 100
                            when 'per_tooth' then x.paid * x.rvalue
                            else 0 end, 2)
    from x
   order by x.shipped_at, x.id;
$$;

-- 주문 줄 → JSON 배열 (스냅샷과 화면이 같은 모양)
create or replace function public._commission_items(p_year integer, p_month integer, p_rep uuid)
returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'order_id', c.order_id, 'clinic', c.clinic, 'shipped_at', c.shipped_at,
           'teeth', c.teeth, 'paid_teeth', c.paid_teeth, 'revenue', c.revenue,
           'rate_type', c.rate_type, 'rate_value', c.rate_value, 'commission', c.commission)
         order by c.shipped_at, c.order_id), '[]'::jsonb)
    from public._commission_rows(p_year, p_month, p_rep) c;
$$;

-- 한 달 결과 (p_only_rep 가 있으면 그 사람만): 지급 완료된 사람은 스냅샷 그대로, 나머지는 지금 계산
create or replace function public._commission_month_json(p_year integer, p_month integer, p_only_rep uuid)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_reps jsonb := '[]'::jsonb;
  r record;
  v_items jsonb;
  v_pay record;
  v_today date := (now() at time zone 'Asia/Bangkok')::date;
begin
  for r in
    select s.user_id, s.active and exists (select 1 from public.admins a where a.user_id = s.user_id) as active
      from public.sales_reps s
     where (p_only_rep is not null and s.user_id = p_only_rep)
        or (p_only_rep is null and (
              s.active
           or exists (select 1 from public.cnc_orders o
                       where o.sales_rep_id = s.user_id and o.stage <> 'cancelled'
                         and o.shipped_at >= public._bkk_month_start(p_year, p_month)
                         and o.shipped_at <  public._bkk_month_end(p_year, p_month))
           or exists (select 1 from public.commission_payouts c
                       where c.rep_id = s.user_id and c.year = p_year and c.month = p_month)))
     order by public._admin_name(s.user_id)
  loop
    select * into v_pay from public.commission_payouts c
     where c.rep_id = r.user_id and c.year = p_year and c.month = p_month;
    if found then
      v_items := v_pay.orders;
    else
      v_items := public._commission_items(p_year, p_month, r.user_id);
    end if;
    v_reps := v_reps || jsonb_build_array(jsonb_build_object(
      'rep_id', r.user_id, 'name', public._admin_name(r.user_id), 'active', r.active,
      'orders', jsonb_array_length(v_items),
      'teeth', coalesce((select sum((i ->> 'teeth')::int) from jsonb_array_elements(v_items) i), 0),
      'paid_teeth', coalesce((select sum((i ->> 'paid_teeth')::int) from jsonb_array_elements(v_items) i), 0),
      'revenue', coalesce((select sum((i ->> 'revenue')::numeric) from jsonb_array_elements(v_items) i), 0),
      'commission', case when v_pay.id is not null then v_pay.total
                         else coalesce((select sum((i ->> 'commission')::numeric) from jsonb_array_elements(v_items) i), 0) end,
      'rate', (select jsonb_build_object('type', x.type, 'value', x.value, 'effective_from', x.effective_from)
                 from public.sales_rep_rates x
                where x.rep_id = r.user_id and x.effective_from <= least(v_today, (public._bkk_month_end(p_year, p_month) at time zone 'Asia/Bangkok')::date - 1)
                order by x.effective_from desc, x.created_at desc, x.id desc limit 1),
      'paid', case when v_pay.id is null then null else jsonb_build_object(
                'paid_at', v_pay.paid_at, 'paid_by_name', case when v_pay.paid_by is null then '' else public._admin_name(v_pay.paid_by) end,
                'note', v_pay.note, 'total', v_pay.total) end,
      'items', v_items));
    v_pay := null;
  end loop;

  return jsonb_build_object(
    'year', p_year, 'month', p_month,
    'month_ended', (make_date(p_year, p_month, 1) + interval '1 month')::date <= v_today,
    'reps', v_reps);
end $$;

-- 관리자 (owner): 직원별 + 담당 미지정 배송 주문 수
create or replace function public.admin_commission_month(p_year integer, p_month integer)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare v jsonb;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if p_month is null or p_month not between 1 and 12 or p_year is null then raise exception 'INVALID_MONTH'; end if;
  v := public._commission_month_json(p_year, p_month, null);
  return v || jsonb_build_object('unassigned', (
    select count(*) from public.cnc_orders o
     where o.sales_rep_id is null and o.stage <> 'cancelled'
       and o.shipped_at >= public._bkk_month_start(p_year, p_month)
       and o.shipped_at <  public._bkk_month_end(p_year, p_month)));
end $$;

-- 영업 본인: 자기 것만
create or replace function public.my_commission_month(p_year integer, p_month integer)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if auth.uid() is null or not exists (select 1 from public.sales_reps where user_id = auth.uid()) then
    raise exception 'NOT_SALES';
  end if;
  if p_month is null or p_month not between 1 and 12 or p_year is null then raise exception 'INVALID_MONTH'; end if;
  return public._commission_month_json(p_year, p_month, auth.uid());
end $$;

-- 영업 본인: 내 담당 주문 (환자 · 파일 · 연락처 · 주소는 빼요)
create or replace function public.sales_my_orders(p_limit integer default 300)
returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  if auth.uid() is null or not exists (select 1 from public.sales_reps where user_id = auth.uid()) then
    raise exception 'NOT_SALES';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', o.id, 'clinic', o.clinic, 'teeth_count', o.teeth_count, 'stage', o.stage,
             'shipped_at', o.shipped_at, 'created_at', o.created_at)
           order by o.created_at desc)
      from (select * from public.cnc_orders where sales_rep_id = auth.uid()
             order by created_at desc limit greatest(1, least(coalesce(p_limit, 300), 1000))) o), '[]'::jsonb);
end $$;


-- ================================================================
-- 9) 정산 (owner) — 지급 완료 = 스냅샷 + 잠금 / 취소 = 사유 필수
-- ================================================================
create or replace function public.admin_mark_commission_paid(p_rep uuid, p_year integer, p_month integer, p_note text default '')
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_items jsonb;
  v_total numeric;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if p_month is null or p_month not between 1 and 12 or p_year is null then raise exception 'INVALID_MONTH'; end if;
  if not exists (select 1 from public.sales_reps where user_id = p_rep) then raise exception 'REP_NOT_FOUND'; end if;
  -- 달이 끝나야 지급 완료 (그 달에 배송될 주문이 더 남아 있을 수 있어서)
  if (make_date(p_year, p_month, 1) + interval '1 month')::date > (now() at time zone 'Asia/Bangkok')::date then
    raise exception 'MONTH_NOT_ENDED';
  end if;
  if exists (select 1 from public.commission_payouts where rep_id = p_rep and year = p_year and month = p_month) then
    raise exception 'ALREADY_PAID';
  end if;
  v_items := public._commission_items(p_year, p_month, p_rep);
  v_total := coalesce((select sum((i ->> 'commission')::numeric) from jsonb_array_elements(v_items) i), 0);
  insert into public.commission_payouts (rep_id, year, month, total, orders, paid_at, paid_by, note)
  values (p_rep, p_year, p_month, round(v_total, 2), v_items, now(), auth.uid(), left(trim(coalesce(p_note, '')), 300));
  perform public._audit('commission_paid', 'member', p_rep::text, jsonb_build_object(
    'name', public._admin_name(p_rep), 'year', p_year, 'month', p_month, 'total', round(v_total, 2),
    'orders', jsonb_array_length(v_items), 'note', trim(coalesce(p_note, ''))));
  return jsonb_build_object('total', round(v_total, 2), 'orders', jsonb_array_length(v_items));
end $$;

create or replace function public.admin_unmark_commission_paid(p_rep uuid, p_year integer, p_month integer, p_reason text)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_total numeric;
begin
  if not public.has_admin_role('owner') then raise exception 'NOT_ADMIN'; end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'REASON_REQUIRED'; end if;
  delete from public.commission_payouts where rep_id = p_rep and year = p_year and month = p_month
  returning total into v_total;
  if not found then raise exception 'NOT_PAID'; end if;
  perform public._audit('commission_unpaid', 'member', p_rep::text, jsonb_build_object(
    'name', public._admin_name(p_rep), 'year', p_year, 'month', p_month, 'total', v_total, 'reason', trim(p_reason)));
  return jsonb_build_object('total', v_total);
end $$;


