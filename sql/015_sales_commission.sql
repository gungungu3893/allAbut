create or replace function public.is_sales_rep()
returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.sales_reps r join public.admins a on a.user_id = r.user_id
     where r.user_id = auth.uid() and r.active);
$$;

create or replace function public.my_sales_rep_id()
returns uuid
language sql stable security definer set search_path = public as $$
  select case when public.is_sales_rep() then auth.uid() else null end;
$$;

