-- ================================================================
-- 5) 트리거 — 담당자 자동 복사 · 직접 수정 막기 · 배송 시각
-- ================================================================
-- 관리자 함수 안에서만 set_config('allabut.rep_ok', '1', true) → 담당자 칸을 바꿀 수 있어요
create or replace function public._rep_change_ok()
returns boolean language sql stable as $$
  select coalesce(current_setting('allabut.rep_ok', true), '') = '1';
$$;

-- 주문
create or replace function public._trg_orders_sales_rep()
returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    -- 새 주문 = 고객의 담당자(켜진 담당자만) 자동 복사. 보낸 값은 무시
    if not public._rep_change_ok() then
      select p.sales_rep_id into new.sales_rep_id
        from public.profiles p join public.sales_reps r on r.user_id = p.sales_rep_id and r.active
       where p.id = new.user_id;
    end if;
    new.shipped_at := case when new.stage in ('shipped', 'done') then coalesce(new.shipped_at, now()) else null end;
    return new;
  end if;

  -- 담당자: 관리자 함수로만 (고객 · staff 의 직접 수정은 조용히 되돌려요)
  if new.sales_rep_id is distinct from old.sales_rep_id and not public._rep_change_ok() then
    new.sales_rep_id := old.sales_rep_id;
  end if;
  -- 배송 시각: 직접 못 고쳐요 (이 파일의 처음 채우기만 예외). 처음 shipped 가 되는 순간에만 지금 시각
  if not public._rep_change_ok() then new.shipped_at := old.shipped_at; end if;
  if old.shipped_at is null and new.stage in ('shipped', 'done') and old.stage is distinct from new.stage then
    new.shipped_at := now();
  end if;
  return new;
end $$;
drop trigger if exists trg_orders_sales_rep on public.cnc_orders;
create trigger trg_orders_sales_rep before insert or update on public.cnc_orders
  for each row execute function public._trg_orders_sales_rep();

-- 고객 프로필 (고객이 자기 프로필을 직접 고칠 수 있어서 → 담당자 칸은 되돌려요)
create or replace function public._trg_profile_sales_rep()
returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if public._rep_change_ok() or auth.uid() is null then return new; end if;
  if tg_op = 'INSERT' then
    new.sales_rep_id := null;
  elsif new.sales_rep_id is distinct from old.sales_rep_id then
    new.sales_rep_id := old.sales_rep_id;
  end if;
  return new;
end $$;
drop trigger if exists trg_profile_sales_rep on public.profiles;
create trigger trg_profile_sales_rep before insert or update on public.profiles
  for each row execute function public._trg_profile_sales_rep();

-- 팀원: 역할이 'sales' 가 되면 영업 담당으로 켜요 / 팀에서 빠지면 영업 담당 끄기 (기록은 남겨요)
create or replace function public._trg_admins_sales_rep()
returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    update public.sales_reps set active = false where user_id = old.user_id;
    return old;
  end if;
  if new.role = 'sales' and (tg_op = 'INSERT' or old.role is distinct from 'sales') then
    insert into public.sales_reps (user_id, active) values (new.user_id, true)
    on conflict (user_id) do update set active = true;
  end if;
  return new;
end $$;
drop trigger if exists trg_admins_sales_rep on public.admins;
create trigger trg_admins_sales_rep after insert or update of role or delete on public.admins
  for each row execute function public._trg_admins_sales_rep();

-- 이미 배송된 주문의 배송 시각 채우기: review_history 의 마지막 'shipped' 기록 → 없으면 updated_at
-- (트리거가 직접 수정을 되돌리므로 허용 표시를 켜고 채워요. 이미 채워진 주문은 건너뜀)
select set_config('allabut.rep_ok', '1', false);
update public.cnc_orders o
   set shipped_at = coalesce(
         (select max(public._safe_ts(e ->> 'date'))
            from jsonb_array_elements(case when jsonb_typeof(o.review_history) = 'array' then o.review_history else '[]'::jsonb end) e
           where e ->> 'action' = 'shipped'),
         o.updated_at)
 where o.shipped_at is null and o.stage in ('shipped', 'done');
select set_config('allabut.rep_ok', '0', false);

-- 이미 sales 역할인 팀원(두 번째 실행 등)은 영업 담당으로
insert into public.sales_reps (user_id, active)
select user_id, true from public.admins where role = 'sales'
on conflict (user_id) do nothing;


